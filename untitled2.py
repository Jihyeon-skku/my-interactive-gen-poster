    cmap = LinearSegmentedColormap.from_list("theme", colors)

    S = 160                                          # segments along the ribbon
    t = np.linspace(0, 1, S + 1)                     # 0 = ribbon start, 1 = ribbon end
    u = np.linspace(-0.5, 0.5, n_layers + 1)         # -0.5 = inner edge, 0.5 = outer edge

    # Path of the ribbon: an arch that sweeps from lower-left, over the top, to lower-right.
    theta = np.deg2rad(200 - 225 * t)
    R = 3.1 + 0.35 * np.sin(2 * np.pi * 0.8 * t + 0.5)          # distance from the center
    width = 0.5 + 1.6 * np.sin(np.pi * t) ** 1.1                # ribbon is widest in the middle

    # Ruffles: the outer edge ruffles more than the inner edge.
    noise = ridge_noise(t, u, SEED)
    envelope = 0.25 + 0.75 * (u[:, None] + 0.5)
    radial = R[None, :] + u[:, None] * width[None, :] + wobble * 0.5 * envelope * noise
    X = CENTER_X + radial * np.cos(theta)[None, :]
    Y = CENTER_Y + radial * np.sin(theta)[None, :]

    # Soft glow under the ribbon (a few wide, very transparent lines).
    cx_line = CENTER_X + R * np.cos(theta)
    cy_line = CENTER_Y + R * np.sin(theta)
    for lw, a in ((70, 0.03), (45, 0.04), (25, 0.05)):
        ax.plot(cx_line, cy_line, color=cmap(0.5), linewidth=lw, alpha=a,
                solid_capstyle="round", zorder=1)

    # Build one small quadrilateral for every (band, segment) pair.
    p00 = np.stack([X[:-1, :-1], Y[:-1, :-1]], axis=-1)
    p01 = np.stack([X[:-1, 1:],  Y[:-1, 1:]],  axis=-1)
    p11 = np.stack([X[1:, 1:],   Y[1:, 1:]],   axis=-1)
    p10 = np.stack([X[1:, :-1],  Y[1:, :-1]],  axis=-1)
    quads = np.stack([p00, p01, p11, p10], axis=2).reshape(-1, 4, 2)

    # Color: mostly by band, slightly by position along the ribbon.

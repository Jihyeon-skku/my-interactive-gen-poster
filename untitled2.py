    seg_pos = (np.arange(S) + 0.5) / S
    pos = 0.7 * band_pos[:, None] + 0.3 * seg_pos[None, :]
    rgb = cmap(pos)[..., :3]

    # Shading: brighter on ridge tops, darker in valleys (gives a 3D feel).

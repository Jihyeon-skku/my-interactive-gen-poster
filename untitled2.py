def ridge_noise(t, u, seed):
    """Smooth, ridge-like noise in the range [-1, 1].
    t = position along the ribbon, u = position across the ribbon.
    Neighboring strands (similar u) get similar values, so the ridges flow."""
    rng = np.random.default_rng(seed)
    total = np.zeros((len(u), len(t)))
    norm = 0.0
    for k, freq in enumerate((3, 6, 11, 17, 26)):     # low to high frequency
        amp = 1.0 / (k + 1)
        phase = rng.uniform(0, 2 * np.pi)
        coupling = rng.uniform(-4, 4)
        total += amp * np.sin(2 * np.pi * freq * t[None, :] + phase + coupling * u[:, None])
        norm += amp
    return total / norm


    ax.scatter(rng.uniform(0.6, POSTER_W - 0.6, 40),
               rng.uniform(1.8, POSTER_H - 0.6, 40),
               s=rng.uniform(1, 6, 40), color=ink, alpha=0.5,
               linewidths=0, zorder=2)

